"""Generate the committed mapping index (``cache/_mapping_index.py``, #903).

``ModelRegistry`` registers mappings lazily from this index, so startup never imports the
~470 ``mapping.py`` modules.  The index is built by executing each ``mapping.py`` against a
recording stand-in for ``register_mapping``, so it holds the real registered name and model
class rather than a text-scan guess.  Run ``doit mapping_index`` after adding, renaming or
removing a mapping, and ``doit mapping_index --check`` to detect drift.
"""

from __future__ import annotations

import difflib
import importlib.util
import json
import sys
from pathlib import Path

from pynetappfoundry.cache._registry import model_registry
from pynetappfoundry.cache.field_mapping import TypeMapping
from pynetappfoundry.cache.overlay_loader import discover_toml_overlays

_PACKAGE = "pynetappfoundry.cache"
_CACHE_ROOT = Path("src/pynetappfoundry/cache")
_INDEX_PATH = _CACHE_ROOT / "_mapping_index.py"
_API_DIRS = ("ontap", "dii")

IndexRow = tuple[str, str, str, str | None]

_HEADER = '''\
"""Index of every cache mapping module, generated by ``doit mapping_index`` (#903).

DO NOT EDIT.  Maps each registered mapping name to ``(mapping module, model module, model
qualname, package overlay path relative to cache/ or None)``.  ``ModelRegistry`` imports a
mapping module on first lookup instead of walking every ``mapping.py`` at startup.  After adding,
renaming or removing a mapping, run ``doit mapping_index``; ``doit mapping_index --check``
reports drift.
"""

from __future__ import annotations

MAPPING_INDEX: dict[str, tuple[str, str, str, str | None]] = {
'''


def _find_mapping_files(cache_root: Path) -> list[Path]:
    files: list[Path] = []
    for api_dir in _API_DIRS:
        files.extend((cache_root / api_dir).rglob("mapping.py"))
    return sorted(files, key=lambda p: p.relative_to(cache_root).as_posix())


def _module_name(path: Path, cache_root: Path) -> str:
    parts = path.relative_to(cache_root).with_suffix("").parts
    return ".".join((_PACKAGE, *parts))


def _record_registrations(path: Path, module_name: str) -> list[tuple[str, TypeMapping]]:
    """Execute *path* in a throwaway module and return its ``register_mapping`` calls."""
    calls: list[tuple[str, TypeMapping]] = []

    def recorder(name: str, mapping: TypeMapping) -> None:
        calls.append((name, mapping))

    probe_name = f"_mapping_index_probe.{module_name}"
    spec = importlib.util.spec_from_file_location(probe_name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[probe_name] = module
    # Instance attribute shadows the method, so mapping modules record instead of registering.
    model_registry.register_mapping = recorder  # type: ignore[method-assign]
    try:
        spec.loader.exec_module(module)
    finally:
        del model_registry.register_mapping
        sys.modules.pop(probe_name, None)
    return calls


def build_index(cache_root: Path = _CACHE_ROOT) -> dict[str, IndexRow]:
    """Build the name -> row index by executing every ``mapping.py`` under *cache_root*.

    Raises:
        ValueError: A file registers zero or several mappings, or two mappings share a name
            or a model class.
    """
    overlays = {
        name: path.relative_to(cache_root).as_posix()
        for name, path in discover_toml_overlays(cache_root).items()
    }

    index: dict[str, IndexRow] = {}
    owner_by_name: dict[str, str] = {}
    owner_by_class: dict[tuple[str, str], str] = {}
    for path in _find_mapping_files(cache_root):
        module_name = _module_name(path, cache_root)
        calls = _record_registrations(path, module_name)
        if len(calls) != 1:
            raise ValueError(
                f"{module_name} must call register_mapping exactly once, found {len(calls)}"
            )
        name, mapping = calls[0]
        model_class = mapping.model_class
        key = (model_class.__module__, model_class.__qualname__)
        if name in owner_by_name:
            raise ValueError(
                f"Duplicate mapping name {name!r}: {owner_by_name[name]} and {module_name}"
            )
        if key in owner_by_class:
            raise ValueError(
                f"Duplicate model class {key[0]}.{key[1]}: {owner_by_class[key]} and {module_name}"
            )
        owner_by_name[name] = module_name
        owner_by_class[key] = module_name
        index[name] = (module_name, key[0], key[1], overlays.get(name))
    return dict(sorted(index.items()))


def render_index(index: dict[str, IndexRow]) -> str:
    """Render *index* as the source of ``_mapping_index.py``.

    Every row is written exploded with a trailing comma, the shape ``ruff format`` keeps.
    """
    lines = [_HEADER]
    for name, row in index.items():
        lines.append(f"    {json.dumps(name)}: (\n")
        for item in row:
            text = "None" if item is None else json.dumps(item)
            lines.append(f"        {text},\n")
        lines.append("    ),\n")
    lines.append("}\n")
    return "".join(lines)


def check_index(cache_root: Path = _CACHE_ROOT, index_path: Path | None = None) -> str | None:
    """Compare the committed index with a fresh render.

    Returns:
        ``None`` when they match, otherwise a unified diff of committed -> fresh.
    """
    target = index_path if index_path is not None else cache_root / "_mapping_index.py"
    fresh = render_index(build_index(cache_root))
    committed = target.read_text(encoding="utf-8") if target.exists() else ""
    if committed == fresh:
        return None
    return "".join(
        difflib.unified_diff(
            committed.splitlines(keepends=True),
            fresh.splitlines(keepends=True),
            fromfile=f"{target.as_posix()} (committed)",
            tofile=f"{target.as_posix()} (regenerated)",
        )
    )


def write_index(cache_root: Path = _CACHE_ROOT) -> Path:
    """Regenerate ``_mapping_index.py`` under *cache_root* and return its path."""
    target = cache_root / "_mapping_index.py"
    target.write_text(render_index(build_index(cache_root)), encoding="utf-8", newline="\n")
    return target
