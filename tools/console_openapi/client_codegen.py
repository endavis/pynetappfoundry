"""Generate the typed Console client operation classes (#735, ADR-0019).

Reads the committed Console OpenAPI spec and the curated manifest
``client_ops.toml``, and renders one operations class per client under
``src/pynetappfoundry/clients/console/generated/``.  Each operation becomes a method that
builds the ``APIWrapper.call_endpoint`` arguments and hands them to the client's
dispatch.  Every rule that would otherwise drop information silently is a
``CodegenError`` instead.
"""

from __future__ import annotations

import argparse
import keyword
import re
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

_ROOT = Path(__file__).resolve().parents[2]
SPEC_PATH = _ROOT / "tools/console_openapi/generated/console_openapi.yaml"
MANIFEST_PATH = _ROOT / "tools/console_openapi/client_ops.toml"
MODELS_ROOT = _ROOT / "src/pynetappfoundry/models/console"
OUT_DIR = _ROOT / "src/pynetappfoundry/clients/console/generated"
MODELS_PACKAGE = "pynetappfoundry.models.console"

_REF_PREFIX = "#/components/schemas/"
_METHODS = frozenset({"get", "post", "put", "patch", "delete"})
_NO_RETRY_EXEMPT = frozenset({"GET"})
_CLIENTS: dict[str, tuple[str, str]] = {
    # manifest client -> (module name, class name)
    "console": ("tenancy_ops", "ConsoleTenancyOps"),
    "agent": ("agent_ops", "ConsoleAgentOps"),
}
_HEADER = (
    '"""{what}\n\nGenerated by ``doit console_client`` from '
    "tools/console_openapi/client_ops.toml and the Console OpenAPI spec (#735).\n"
    'Do not edit; edit the manifest and regenerate.\n"""\n'
)
_MANIFEST_KEYS = frozenset(
    {"operation_id", "client", "name", "response", "retry", "only_query", "query"}
)


class CodegenError(ValueError):
    """The manifest or the spec cannot be turned into a client operation."""


@dataclass(frozen=True)
class Param:
    """One path or query parameter."""

    wire: str
    py: str
    csv: bool = False


@dataclass(frozen=True)
class ModelRef:
    """A generated pydantic model: its module name and class."""

    package: str
    module: str
    cls: str


@dataclass(frozen=True)
class Operation:
    """A manifest entry resolved against the spec."""

    client: str
    name: str
    operation_id: str
    http_method: str
    path: str
    summary: str
    token_type: str | None
    path_params: tuple[Param, ...]
    query_params: tuple[Param, ...]
    request: ModelRef | None
    has_body: bool
    response: ModelRef | None
    has_response: bool
    is_list: bool
    retry: bool = False
    models: tuple[ModelRef, ...] = field(default=(), compare=False)


def snake_case(name: str) -> str:
    """Return ``name`` as a snake_case Python identifier (keywords get a ``_`` suffix)."""
    out = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name.replace("-", "_")).lower()
    if not out.isidentifier():
        raise CodegenError(f"Cannot make an identifier from {name!r}")
    return f"{out}_" if keyword.iskeyword(out) else out


def load_manifest(path: Path = MANIFEST_PATH) -> list[dict[str, Any]]:
    """Return the manifest's ``[[operation]]`` entries, checking their keys."""
    with path.open("rb") as f:
        data = tomllib.load(f)
    entries: list[dict[str, Any]] = data.get("operation", [])
    for entry in entries:
        unknown = set(entry) - _MANIFEST_KEYS
        if unknown:
            raise CodegenError(f"Unknown manifest keys {sorted(unknown)} in {entry}")
        for key in ("operation_id", "client", "name"):
            if key not in entry:
                raise CodegenError(f"Manifest entry is missing {key!r}: {entry}")
        if entry["client"] not in _CLIENTS:
            raise CodegenError(f"Unknown client {entry['client']!r} for {entry['operation_id']}")
        if entry.get("response", "object") not in ("object", "list"):
            raise CodegenError(f"Unknown response {entry['response']!r} for {entry['name']}")
        if not str(entry["name"]).isidentifier() or keyword.iskeyword(entry["name"]):
            raise CodegenError(f"{entry['name']!r} is not a valid method name")
    return entries


def load_spec(path: Path = SPEC_PATH) -> dict[str, Any]:
    """Return the parsed Console OpenAPI spec."""
    with path.open(encoding="utf-8") as f:
        spec: dict[str, Any] = yaml.safe_load(f)
    return spec


def _index_operations(spec: dict[str, Any]) -> dict[str, tuple[str, str, dict[str, Any]]]:
    """Map operationId -> (path, HTTP method, operation object)."""
    index: dict[str, tuple[str, str, dict[str, Any]]] = {}
    for path, item in spec.get("paths", {}).items():
        for method, op in item.items():
            if method in _METHODS and isinstance(op, dict) and "operationId" in op:
                index[op["operationId"]] = (path, method.upper(), op)
    return index


def _model_ref(schema: Any, kind: str, models_root: Path) -> ModelRef | None:
    """Return the named model a schema refers to, checked against the models tree."""
    if not isinstance(schema, dict) or "$ref" not in schema:
        return None
    ref = str(schema["$ref"])
    if not ref.startswith(_REF_PREFIX):
        raise CodegenError(f"Unsupported $ref {ref!r}")
    name = ref.removeprefix(_REF_PREFIX)
    head, _, cls = name.rpartition(".")
    package, _, stem = head.partition(".")
    # A numeric success status hoists as ``Response<status>Body`` (#1027).
    named = cls == kind or (kind == "ResponseBody" and re.fullmatch(r"Response\d{3}Body", cls))
    if not named or not package or not stem:
        raise CodegenError(f"Cannot map {ref!r} to a generated {kind} model")
    module = stem.replace("-", "_")
    file = models_root / package / f"{module}.py"
    if not file.is_file():
        raise CodegenError(f"Model module {file} for {ref!r} does not exist")
    if f"class {cls}(" not in file.read_text(encoding="utf-8"):
        raise CodegenError(f"Model module {file} does not define {cls}")
    return ModelRef(package, module, cls)


def _json_schema(content: Any) -> Any:
    if not isinstance(content, dict):
        return None
    media = content.get("application/json")
    return media.get("schema") if isinstance(media, dict) else None


def _response_schema(responses: dict[str, Any]) -> tuple[bool, Any]:
    """Return (has a body, its schema) for the success response (lowest 2xx, else default)."""
    codes = sorted(c for c in responses if str(c).startswith("2"))
    if not codes and "default" in responses:
        codes = ["default"]
    if not codes:
        return False, None
    content = responses[codes[0]].get("content")
    if not content:
        return False, None
    return True, _json_schema(content)


def resolve_operation(
    entry: dict[str, Any],
    index: dict[str, tuple[str, str, dict[str, Any]]],
    models_root: Path = MODELS_ROOT,
) -> Operation:
    """Resolve one manifest entry against the spec, applying every codegen rule."""
    op_id = entry["operation_id"]
    if op_id not in index:
        raise CodegenError(f"operationId {op_id!r} is not in the spec")
    path, method, op = index[op_id]
    name = entry["name"]

    token_type = op.get("x-token-type")
    if token_type not in (None, "user", "service"):
        raise CodegenError(f"{op_id}: unknown x-token-type {token_type!r}")
    if entry["client"] == "agent" and token_type is not None:
        raise CodegenError(
            f"{op_id}: the agent client has one credential, but the operation sets "
            f"x-token-type {token_type!r}"
        )

    overlays: dict[str, Any] = entry.get("query", {})
    only: list[str] | None = entry.get("only_query")
    path_params: list[Param] = []
    query_params: list[Param] = []
    seen_query: set[str] = set()
    for param in op.get("parameters", []):
        where, wire = param["in"], param["name"]
        if where == "header":
            if wire == "x-agent-id" and param.get("x-synthesized") is True:
                continue
            raise CodegenError(f"{op_id}: unsupported header parameter {wire!r}")
        if where == "path":
            path_params.append(Param(wire, snake_case(wire)))
        elif where == "query":
            seen_query.add(wire)
            if only is not None and wire not in only:
                continue
            style = overlays.get(wire, {}).get("style")
            if style not in (None, "csv"):
                raise CodegenError(f"{op_id}: unknown style {style!r} for {wire!r}")
            if style is None and param.get("schema", {}).get("type") != "string":
                raise CodegenError(
                    f"{op_id}: query parameter {wire!r} is not a plain string; "
                    "give it an overlay in the manifest"
                )
            query_params.append(Param(wire, snake_case(wire), csv=style == "csv"))
        else:
            raise CodegenError(f"{op_id}: unsupported {where} parameter {wire!r}")
    missing = (set(overlays) | set(only or [])) - seen_query
    if missing:
        raise CodegenError(f"{op_id}: manifest names unknown query parameters {sorted(missing)}")
    py_names = [p.py for p in (*path_params, *query_params)]
    if len(set(py_names)) != len(py_names) or "body" in py_names:
        raise CodegenError(f"{op_id}: parameter names collide: {py_names}")

    request_body = op.get("requestBody")
    request = None
    has_body = request_body is not None
    if request_body is not None:
        request = _model_ref(_json_schema(request_body.get("content")), "RequestBody", models_root)

    has_response, schema = _response_schema(op.get("responses", {}))
    response = _model_ref(schema, "ResponseBody", models_root) if has_response else None

    return Operation(
        client=entry["client"],
        name=name,
        operation_id=op_id,
        http_method=method,
        path=path,
        summary=str(op.get("summary") or name),
        token_type=token_type,
        path_params=tuple(path_params),
        query_params=tuple(query_params),
        request=request,
        has_body=has_body,
        response=response,
        has_response=has_response,
        is_list=entry.get("response", "object") == "list",
        retry=bool(entry.get("retry", False)),
        models=tuple(m for m in (request, response) if m is not None),
    )


def resolve_all(
    manifest: list[dict[str, Any]], spec: dict[str, Any], models_root: Path = MODELS_ROOT
) -> dict[str, list[Operation]]:
    """Resolve the manifest, grouped by client, rejecting duplicate names."""
    index = _index_operations(spec)
    by_client: dict[str, list[Operation]] = {}
    seen: set[tuple[str, str]] = set()
    for entry in manifest:
        op = resolve_operation(entry, index, models_root)
        key = (op.client, op.name)
        if key in seen:
            raise CodegenError(f"Duplicate method name {op.name!r} for client {op.client!r}")
        seen.add(key)
        by_client.setdefault(op.client, []).append(op)
    return by_client


def _clean(text: str) -> str:
    """Make ``text`` safe inside a triple-quoted docstring."""
    return " ".join(text.replace("\\", "/").replace('"', "'").split())


def _model_alias(ref: ModelRef) -> str:
    return ref.module


def _return_type(op: Operation) -> str:
    if not op.has_response:
        return "None"
    inner = f"{_model_alias(op.response)}.{op.response.cls}" if op.response else "dict[str, Any]"
    if op.is_list:
        return f"list[{inner}]" if op.response else "list[Any]"
    return inner


def _render_method(op: Operation) -> str:
    args = ["self"]
    args += [f"{p.py}: str" for p in op.path_params]
    if op.has_body:
        args.append(f"body: {_body_type(op)}")
    if op.query_params:
        args.append("*")
        args += [
            f"{p.py}: {'str | Sequence[str] | None' if p.csv else 'str | None'} = None"
            for p in op.query_params
        ]
    lines = [
        f"    def {op.name}({', '.join(args)}) -> {_return_type(op)}:",
        f'        """{op.http_method} {op.path}: {_clean(op.summary)}.',
        "",
        f"        operationId: {op.operation_id} (generated; do not edit).",
        '        """',
    ]
    if op.response is not None:
        r = op.response
        lines.append(f"        from {MODELS_PACKAGE}.{r.package} import {r.module}")
        lines.append("")
    lines.append(
        f'        kwargs: dict[str, Any] = {{"method": "{op.http_method}", '
        f'"path_template": "{op.path}"}}'
    )
    if op.path_params:
        items = ", ".join(f'"{p.wire}": quote({p.py}, safe="")' for p in op.path_params)
        lines.append(f'        kwargs["path_params"] = {{{items}}}')
    if op.query_params:
        items = ", ".join(
            f'"{p.wire}": ' + (f"csv_param({p.py})" if p.csv else p.py) for p in op.query_params
        )
        lines += [
            f"        query = drop_none({{{items}}})",
            "        if query:",
            '            kwargs["query_params"] = query',
        ]
    if op.has_body:
        lines.append(
            '        kwargs["body"] = body.model_dump(exclude_none=True)'
            if op.request is not None
            else '        kwargs["body"] = body'
        )
    if op.http_method not in _NO_RETRY_EXEMPT and not op.retry:
        lines.append('        kwargs["retry_config"] = RetryConfig(enabled=False)')
    token = f'"{op.token_type}"' if op.token_type else "None"
    call = f"self._dispatch({token}, **kwargs)"
    if not op.has_response:
        lines.append(f"        {call}")
        return "\n".join(lines)
    lines.append(f"        response = {call}")
    if op.response is None:
        fn = "expect_list" if op.is_list else "expect_object"
        lines.append(f'        return {fn}(response, "{op.name}")')
    elif op.is_list:
        lines.append(
            f"        return [{op.response.module}.{op.response.cls}.model_validate(i) "
            f'for i in expect_list(response, "{op.name}")]'
        )
    else:
        lines.append(
            f"        return {op.response.module}.{op.response.cls}.model_validate("
            f'expect_object(response, "{op.name}"))'
        )
    return "\n".join(lines)


def _body_type(op: Operation) -> str:
    if op.request is None:
        return "dict[str, Any]"
    return f"{_model_alias(op.request)}.{op.request.cls}"


def render_module(client: str, operations: list[Operation]) -> str:
    """Render the operations module for one client (unformatted; ruff formats it)."""
    _, cls = _CLIENTS[client]
    typing_models = sorted({(m.package, m.module) for op in operations for m in op.models})
    uses_csv = any(p.csv for op in operations for p in op.query_params)
    uses_quote = any(op.path_params for op in operations)
    uses_retry = any(op.http_method not in _NO_RETRY_EXEMPT and not op.retry for op in operations)
    support = ["Dispatch"]
    if uses_csv:
        support.append("csv_param")
    if any(op.query_params for op in operations):
        support.append("drop_none")
    if any(op.has_response and op.is_list for op in operations):
        support.append("expect_list")
    if any(op.has_response and not op.is_list for op in operations):
        support.append("expect_object")
    out = [_HEADER.format(what=f"Generated Console operations for the {client} client.")]
    out.append("from __future__ import annotations\n")
    if uses_csv:
        out.append("from collections.abc import Sequence")
    out.append("from typing import TYPE_CHECKING, Any")
    if uses_quote:
        out.append("from urllib.parse import quote")
    out.append("")
    out.append(
        "from pynetappfoundry.clients.console._ops_support import " + ", ".join(sorted(support))
    )
    if uses_retry:
        out.append("from pynetappfoundry.core.models import RetryConfig")
    out.append("")
    if typing_models:
        out.append("if TYPE_CHECKING:")
        for package, module_name in typing_models:
            out.append(f"    from {MODELS_PACKAGE}.{package} import {module_name}")
        out.append("")
    out.append("")
    out.append(f"class {cls}:")
    out.append(f'    """Typed operations for the {client} client."""')
    out.append("")
    out.append("    def __init__(self, dispatch: Dispatch) -> None:")
    out.append('        """Bind the operations to a client\'s dispatch."""')
    out.append("        self._dispatch = dispatch")
    for op in operations:
        out.append("")
        out.append(_render_method(op))
    out.append("")
    out.append("")
    out.append(f'__all__ = ["{cls}"]')
    out.append("")
    return "\n".join(out)


def render_all(
    manifest: list[dict[str, Any]], spec: dict[str, Any], models_root: Path = MODELS_ROOT
) -> dict[str, str]:
    """Return ``{file name: source}`` for every generated file."""
    grouped = resolve_all(manifest, spec, models_root)
    files: dict[str, str] = {}
    imports: list[str] = []
    names: list[str] = []
    for client in _CLIENTS:
        if client not in grouped:
            continue
        module, cls = _CLIENTS[client]
        files[f"{module}.py"] = render_module(client, grouped[client])
        imports.append(f"from pynetappfoundry.clients.console.generated.{module} import {cls}")
        names.append(f'"{cls}"')
    files["__init__.py"] = (
        _HEADER.format(what="Generated Console operation classes.")
        + "\n"
        + "\n".join(imports)
        + f"\n\n__all__ = [{', '.join(sorted(names))}]\n"
    )
    return files


def generate(
    out_dir: Path = OUT_DIR,
    spec_path: Path = SPEC_PATH,
    manifest_path: Path = MANIFEST_PATH,
    models_root: Path = MODELS_ROOT,
) -> list[Path]:
    """Write the generated files under ``out_dir`` and return their paths."""
    files = render_all(load_manifest(manifest_path), load_spec(spec_path), models_root)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, source in sorted(files.items()):
        target = out_dir / name
        target.write_text(source, encoding="utf-8")
        written.append(target)
    return written


def main(argv: list[str] | None = None) -> int:
    """Generate the client operation classes (unformatted; the doit task formats them)."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    args = parser.parse_args(argv)
    for path in generate(args.out):
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
