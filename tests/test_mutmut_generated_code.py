"""Keep ``do_not_mutate`` in ``[tool.mutmut]`` in step with generated code (#1137).

mutmut 3 mutates only code inside functions. Generated files that define one
produce mutants that test the generator, not our tests, so they are excluded.
mutmut matches each pattern with ``fnmatch.fnmatch`` on the repo-relative path.
"""

from __future__ import annotations

import ast
import fnmatch
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
SRC = REPO_ROOT / "src"
MARKER_LINES = 6


def _patterns() -> list[str]:
    with (REPO_ROOT / "pyproject.toml").open("rb") as f:
        config = tomllib.load(f)
    patterns: list[str] = config["tool"]["mutmut"].get("do_not_mutate", [])
    return patterns


def _is_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:MARKER_LINES])
    return "generated by" in head.lower()


def _defines_function(text: str) -> bool:
    tree = ast.parse(text)
    return any(isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef) for n in ast.walk(tree))


def _is_generated_with_function(text: str) -> bool:
    return _is_generated(text) and _defines_function(text)


def _matched(path: Path, patterns: list[str]) -> bool:
    rel = path.relative_to(REPO_ROOT).as_posix()
    return any(fnmatch.fnmatch(rel, p) for p in patterns)


def _source_files() -> list[Path]:
    return sorted(SRC.rglob("*.py"))


def test_generated_files_with_functions_are_excluded() -> None:
    patterns = _patterns()
    missing = [
        p.relative_to(REPO_ROOT).as_posix()
        for p in _source_files()
        if _is_generated_with_function(p.read_text(encoding="utf-8")) and not _matched(p, patterns)
    ]
    assert not missing, f"Generated files with functions not in do_not_mutate: {missing}"


def test_hand_written_files_are_not_excluded() -> None:
    patterns = _patterns()
    wrongly = [
        p.relative_to(REPO_ROOT).as_posix()
        for p in _source_files()
        if not _is_generated(p.read_text(encoding="utf-8")) and _matched(p, patterns)
    ]
    assert not wrongly, f"do_not_mutate matches hand-written files: {wrongly}"


def test_patterns_are_valid_and_not_stale() -> None:
    files = _source_files()
    for pattern in _patterns():
        assert pattern.endswith(("*", ".py")), f"mutmut rejects pattern {pattern!r}"
        assert any(fnmatch.fnmatch(f.relative_to(REPO_ROOT).as_posix(), pattern) for f in files), (
            f"Stale do_not_mutate pattern {pattern!r}"
        )


def test_timeout_multiplier_is_lowered_but_positive() -> None:
    """Hanging mutants must not hold a worker for 15x their tests' duration (#1137).

    mutmut 3.8 defaults to 15. Below 1 a mutant would time out before its own
    tests finish, so a killed mutant could be reported as a timeout.
    """
    with (REPO_ROOT / "pyproject.toml").open("rb") as f:
        multiplier = tomllib.load(f)["tool"]["mutmut"].get("timeout_multiplier", 15.0)
    assert isinstance(multiplier, int | float)
    assert 1 <= multiplier < 15


def test_detection_helpers(tmp_path: Path) -> None:
    gen_func = "# Generated by `doit generate_models`\n\ndef f() -> None: ...\n"
    gen_class = "# generated by datamodel-codegen:\n\nclass A:\n    x: int\n"
    hand = "def f() -> None: ...\n"
    files = {"a.py": gen_func, "b.py": gen_class, "c.py": hand}
    for name, text in files.items():
        (tmp_path / name).write_text(text, encoding="utf-8")
    flagged = {
        name
        for name in files
        if _is_generated_with_function((tmp_path / name).read_text(encoding="utf-8"))
    }
    assert flagged == {"a.py"}
